import nodemailer from "nodemailer";

/**
 * Check if SMTP configuration environment variables are present and valid
 */
export const isSmtpConfigured = () => {
  const host = process.env.SMTP_HOST;
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;

  return (
    Boolean(host) &&
    Boolean(user) &&
    Boolean(pass) &&
    host !== "smtp.example.com" &&
    user !== "your_email@gmail.com" &&
    user !== "your_smtp_user@example.com" &&
    pass !== "your_app_password" &&
    pass !== "your_gmail_app_password"
  );
};

/**
 * Create nodemailer transporter instance
 */
const createTransporter = () => {
  if (!isSmtpConfigured()) return null;

  const port = parseInt(process.env.SMTP_PORT || "587", 10);
  const isSecure = port === 465;

  return nodemailer.createTransport({
    host: process.env.SMTP_HOST,
    port: port,
    secure: isSecure, // true for 465, false for 587
    auth: {
      user: process.env.SMTP_USER,
      pass: process.env.SMTP_PASS,
    },
    tls: {
      rejectUnauthorized: false, // Prevents self-signed certificate errors
    },
  });
};

/**
 * Send contact inquiry email to Company / Admin
 * @param {Object} contactData - { name, email, phone, company, message, createdAt }
 */
export const sendContactInquiryEmail = async (contactData) => {
  try {
    if (!isSmtpConfigured()) {
      console.warn(
        "[SMTP Notice] SMTP keys not configured or placeholder values detected in backend/.env. Skipping email delivery."
      );
      return { success: false, reason: "SMTP keys not configured in backend/.env" };
    }

    const transporter = createTransporter();
    if (!transporter) return { success: false, reason: "Failed to initialize SMTP transporter" };

    const recipientEmail =
      process.env.COMPANY_EMAIL ||
      process.env.ADMIN_EMAIL ||
      process.env.SMTP_USER;

    const mailOptions = {
      from: `"FIBC Contact Form" <${process.env.SMTP_USER}>`,
      to: recipientEmail,
      replyTo: contactData.email,
      subject: `New Inquiry from ${contactData.name} - FIBC Website`,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 8px;">
          <h2 style="color: #0f172a; border-bottom: 2px solid #0284c7; padding-bottom: 8px;">
            New Contact Us Inquiry
          </h2>
          <p style="color: #475569; font-size: 14px;">
            A new contact enquiry has been submitted through the FIBC website form:
          </p>

          <table style="width: 100%; border-collapse: collapse; margin-top: 16px;">
            <tr>
              <td style="padding: 8px 0; font-weight: bold; width: 120px; color: #334155;">Client Name:</td>
              <td style="padding: 8px 0; color: #0f172a;">${contactData.name}</td>
            </tr>
            <tr>
              <td style="padding: 8px 0; font-weight: bold; color: #334155;">Email Address:</td>
              <td style="padding: 8px 0; color: #0f172a;">
                <a href="mailto:${contactData.email}" style="color: #0284c7;">${contactData.email}</a>
              </td>
            </tr>
            <tr>
              <td style="padding: 8px 0; font-weight: bold; color: #334155;">Phone Number:</td>
              <td style="padding: 8px 0; color: #0f172a;">${contactData.phone}</td>
            </tr>
            <tr>
              <td style="padding: 8px 0; font-weight: bold; color: #334155;">Company Name:</td>
              <td style="padding: 8px 0; color: #0f172a;">${contactData.company || "N/A"}</td>
            </tr>
            <tr>
              <td style="padding: 8px 0; font-weight: bold; color: #334155;">Submitted At:</td>
              <td style="padding: 8px 0; color: #0f172a;">${new Date(contactData.createdAt || Date.now()).toLocaleString()}</td>
            </tr>
          </table>

          <div style="margin-top: 20px; padding: 16px; background-color: #f8fafc; border-left: 4px solid #0284c7; border-radius: 4px;">
            <h4 style="margin: 0 0 8px 0; color: #1e293b;">Message Payload:</h4>
            <p style="margin: 0; color: #334155; white-space: pre-wrap; font-size: 14px;">${contactData.message}</p>
          </div>

          <p style="margin-top: 24px; font-size: 12px; color: #94a3b8; text-align: center;">
            This email was automatically generated by the FIBC Website Backend API.
          </p>
        </div>
      `,
    };

    const info = await transporter.sendMail(mailOptions);
    console.log("[SMTP Success] Inquiry notification email sent successfully! MessageID:", info.messageId);

    // Send confirmation auto-ack email to client
    sendAutoAcknowledgementEmail(contactData).catch((err) =>
      console.error("[SMTP Warning] Auto-ack email failed:", err.message)
    );

    return { success: true, messageId: info.messageId };
  } catch (error) {
    console.error("[SMTP Error] Failed to send contact inquiry email:", error.message);
    return { success: false, error: error.message };
  }
};

/**
 * Send auto-acknowledgement email back to client
 * @param {Object} contactData
 */
